"""
G. Faça um programa que converta metros em centímetros e milímetros.

Autor: Samuel Gurgel

"""

metros = float(input('Informe um valor em metros: '))
centimetros = metros*100
milimetros = centimetros*100

print(f'{metros} em centimetros: {centimetros} ')
print(f'{metros} em milimetros: {milimetros} ')
