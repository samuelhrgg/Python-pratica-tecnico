"""
Tipos Int e Float
Int → número inteiro (0,1,2,3,...)
O tipo int representa qualquer número positivo ou negativo
Int sem sinal é considerado Positivo!

"""
print("Números inteiros:")
print(11) #inteiro
print(-11) #inteiro negativo
print(0) #inteiro 0

"""
Float → Número com pontos flutuante
O tipo float representa qualquer número positivo 
ou negativo com ponto flutuantes. (0.0 , 0.1, 2.3,...)
Float sem sinal é considerado positivo
Sempre utilizar '.' e não ',' 
"""
print("Números do tipo float:")
print(1.1, 0.2, 0.4) #float

#função type exibe o tipo do valor
print(type(1.5) , 0.0) #float
print(type("Samuel"))