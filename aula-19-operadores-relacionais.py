#aula-19-operadores-relacionais.py
"""
Operadores de comparação (relacionais)
OP      Significado         Exemplo (True)
>       maior               2 > 1
>=      maior ou igual      2 >= 2
<       menor               1 < 2
<=      menor ou igual      2 <= 2
==      igual               'a' == 'a' #serve também com inteiro 3 == 3
!=      diferente           'a' != 'b' # serve também com inteiro 2 != 3

"""
maior = 2 > 1
print(maior)

maior_ou_igual = 2 >= 2
print(maior_ou_igual)

menor = 2 < 3
print(menor)

menor_ou_igual = 4 <= 4
print(menor_ou_igual)

igual = 'a'=='a'
print(igual)

diferente = 'a' != 'b'
print(diferente)
