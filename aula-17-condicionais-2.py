#If, Elif e Else → Funcionamento

condicao = False #variável do tipo bool

if condicao: #Verificar se a condição é verdadeira
    print('Este é o código do IF') #se a condição for verdadeira.

else: #se todas condições forem falsas
    print('Este é o código do Else') #se a condição for falsa.

if 10 == 8: #primeira verificação
    print('Outro IF')

elif 3 < 7: #segundo teste e verificação
    print('Este é o Elif 01')

elif 4 > 10: #terceiro teste e verificação
    print('Este é o Elif 2')

else: #se todas verificações acima forem falsas.
    print('Este é o Else')