"""
Tipo de dado Bool (boolean)
Ao questionar algo em um programa, só existem duas
respostas possíveis: Verdadeiro(True) ou Falso(False)
Existem vários operadores lógicos, entre eles o == que
verifica se um valor é igual a outro.
"""
print(10==10) #Sim → True(Verdadeiro)
print(10==1) #Não → False(Falso)
print(type(True)) #identifica o tipo do valor
print(type(10==10)) #identifica o tipo do valor