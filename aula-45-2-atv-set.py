"""
Métodos para SET { }

1 - add(elemento): Adiciona um elemento ao set.

2- remove(elemento): Remove um elemento do set.
Lança um erro se o elemento não estiver presente.

3 - discard(elemento): Remove um elemento do set se ele estiver presente.
Não faz nada se o elemento não estiver presente.

4 - clear(): Remove todos os elementos do set.

5 - union(set2) ou |: Retorna um novo set que é a união de dois sets.

6 - intersection(set2) ou &: Retorna um novo set que é a
interseção de dois sets.

7 - difference(set2) ou -: Retorna um novo set com os elementos do 
primeiro set que não estão no segundo set.

8 - symmetric_difference(set2) ou ^: Retorna um novo set com elementos
que estão em um dos sets, mas não em ambos.

9 - issubset(set2): Verifica se o set é um subconjunto de outro set.

"""